func bundledFont(t *testing.T) *sfnt.Font {
	t.Helper()
	built, err := buildFont()
	if err != nil {
		t.Fatal(err)
	}
	bundled, err := os.ReadFile(filename)
	if err != nil || !bytes.Equal(built, bundled) {
		t.Fatalf("bundled font must match generated bytes: %v", err)
	}
	again, err := buildFont()
	if err != nil || !bytes.Equal(built, again) {
		t.Fatal("font generation is not deterministic")
	}
	if checksum(built) != 0xB1B0AFBA {
		t.Fatal("invalid OpenType checksum")
	}
	f, err := sfnt.Parse(built)
	if err != nil {
		t.Fatal(err)
	}
	return f
}

func TestFontContract(t *testing.T) {
	f := bundledFont(t)
	name, err := f.Name(nil, sfnt.NameIDFamily)
	if err != nil || name != family || f.NumGlyphs() != 4 || f.UnitsPerEm() != em {
		t.Fatalf("unexpected font metadata: %q, %v", name, err)
	}
	license, err := f.Name(nil, sfnt.NameID(13))
	if err != nil || !strings.Contains(license, "Mozilla Public License 2.0") {
		t.Fatal("missing icon license")
	}
	for i, r := range []rune{'\ue000', '\ue001', '\ue002'} {
		id, err := f.GlyphIndex(nil, r)
		if err != nil || id != sfnt.GlyphIndex(i+1) {
			t.Fatalf("unexpected mapping for %U: %d, %v", r, id, err)
		}
		advance, err := f.GlyphAdvance(nil, id, fixed.I(em), font.HintingNone)
		if err != nil || advance != fixed.I(em) {
			t.Fatalf("unexpected glyph advance: %v, %v", advance, err)
		}
	}
	for _, r := range "Aa0123" {
		id, err := f.GlyphIndex(nil, r)
		if err != nil || id != 0 {
			t.Fatalf("icon font must not replace ordinary text: %U", r)
		}
	}
}

func TestWaybarMapping(t *testing.T) {
	b, err := os.ReadFile("../config.jsonc")
	if err != nil {
		t.Fatal(err)
	}
	var config map[string]struct {
		Format string            `json:"format"`
		Icons  map[string]string `json:"format-icons"`
		Escape bool              `json:"escape"`
	}
	if err := json.Unmarshal(b, &config); err != nil {
		t.Fatal(err)
	}
	c := config["custom/syncshell"]
	if !c.Escape || c.Format != "<span font_family='Syncshell Icons'>{icon}</span>" {
		t.Fatal("scope the icon font to trusted static markup; escape dynamic text")
	}
	for state, want := range map[string]string{
		"default": "\ue000", "healthy": "\ue000", "error": "\ue001",
		"syncing": "\ue002", "scanning": "\ue002", "refreshing": "\ue002",
	} {
		if c.Icons[state] != want {
			t.Errorf("incorrect glyph for %s", state)
		}
	}
}

func render(t *testing.T, svg []byte) image.Image {
	t.Helper()
	cmd := exec.Command("rsvg-convert", "-w", "256", "-h", "256")
	cmd.Stdin = bytes.NewReader(svg)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	output, err := cmd.Output()
	if err != nil {
		t.Fatalf("SVG rendering requires librsvg's rsvg-convert: %v: %s", err, &stderr)
	}
	img, err := png.Decode(bytes.NewReader(output))
	if err != nil {
		t.Fatal(err)
	}
	return img
}

func TestOutlinesMatchSourceSVGs(t *testing.T) {
	f := bundledFont(t)
	for i, name := range []string{"default", "notify", "sync"} {
		t.Run(name, func(t *testing.T) {
			segments, err := f.LoadGlyph(nil, sfnt.GlyphIndex(i+1), fixed.I(em), nil)
			if err != nil {
				t.Fatal(err)
			}
			var path strings.Builder
			for _, s := range segments {
				command, count := "", 0
				switch s.Op {
				case sfnt.SegmentOpMoveTo:
					if path.Len() != 0 {
						path.WriteString("Z ")
					}
					command, count = "M", 1
				case sfnt.SegmentOpLineTo:
					command, count = "L", 1
				case sfnt.SegmentOpQuadTo:
					command, count = "Q", 2
				case sfnt.SegmentOpCubeTo:
					command, count = "C", 3
				default:
					t.Fatalf("unexpected outline operation: %v", s.Op)
				}
				path.WriteString(command)
				for _, p := range s.Args[:count] {
					fmt.Fprintf(&path, " %.6f %.6f", float64(p.X)/4096, 14+float64(p.Y)/4096)
				}
			}
			path.WriteString("Z")
			svg := fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><path fill="white" d="%s"/></svg>`, &path)
			original, err := os.ReadFile("../../../assets/mono/status-" + name + ".svg")
			if err != nil {
				t.Fatal(err)
			}
			want, got := render(t, original), render(t, []byte(svg))
			var difference, coverage float64
			for y := 0; y < 256; y++ {
				for x := 0; x < 256; x++ {
					_, _, _, a := want.At(x, y).RGBA()
					_, _, _, b := got.At(x, y).RGBA()
					difference += float64(max(a, b) - min(a, b))
					coverage += float64(a)
				}
			}
			if coverage == 0 || difference/coverage > 0.015 {
				t.Fatalf("outline differs from source SVG: %.2f%%", 100*difference/coverage)
			}
			t.Logf("SVG alpha difference: %.2f%%", 100*difference/coverage)
		})
	}
}
